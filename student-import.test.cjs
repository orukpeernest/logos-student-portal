const assert=require("node:assert/strict");
const fs=require("node:fs");
const vm=require("node:vm");
const context={window:{}};
vm.runInNewContext(fs.readFileSync("student-import.js","utf8"),context);
const inspect=context.window.LOGOSStudentImport.inspectBackup;
const buildPayload=context.window.LOGOSStudentImport.buildImportPayload;
const valid=inspect({students:[{id:"app-1",surname:"Okoro",first:"Ada",reg:"LGS/26/001"},{id:"app-2",surname:"Adebayo",first:"Tomi",reg:"LGS/26/002"}]});
assert.equal(valid.ok,true);
assert.equal(valid.total,2);
assert.equal(valid.valid,2);
const missingFirst=inspect({students:[{id:"app-1",surname:"Okoro",reg:"LGS/26/001"}]});
assert.equal(missingFirst.ok,false);
assert.equal(missingFirst.issues[0].problems.includes("first name missing"),true);
const raw={students:[{id:"app-1",surname:"Okoro",first:"Ada",reg:"LGS/26/001",phone:"000",photo:"PRIVATE-BASE64",fee:15000,cycle:"A"},{id:"app-2",surname:"Adebayo",first:"Tomi",reg:"LGS/26/002",photo:"PRIVATE-BASE64"}]};
const safePayload=buildPayload(raw);
assert.equal(safePayload.length,2);
assert.equal(safePayload[0].id,"app-1");
assert.equal(safePayload[0].fee,"15000");
assert.equal(safePayload[0].cycle,"A");
assert.equal(Object.hasOwn(safePayload[0],"photo"),false);
assert.equal(JSON.stringify(safePayload).includes("PRIVATE-BASE64"),false);
assert.throws(()=>buildPayload({students:[{id:"x",surname:"",first:"",reg:"123"}]}));
const duplicate=inspect({students:[{id:"app-1",surname:"Okoro",first:"Ada",reg:"LGS/26/001"},{id:"app-2",surname:"Okoro",first:"Tomi",reg:"ABC/16/001"}]});
assert.equal(duplicate.ok,false);
assert.equal(duplicate.duplicateLogins,1);
const malformed=inspect({students:[{surname:"",first:"",reg:"123"}]});
assert.equal(malformed.invalid,1);
assert.equal(malformed.issues[0].problems.length,4);
assert.equal(inspect({records:[]}).ok,false);
assert.equal(inspect({students:[]}).ok,false);
process.stdout.write("Student import validation tests passed.\\n");
